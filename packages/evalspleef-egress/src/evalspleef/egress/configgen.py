"""Squid and Envoy configuration generators for the same egress allowlist.

These generators express the host allowlist, the blocklist, the metadata CIDRs and the
read-only method set. They are configuration text only: the files they emit have NOT been
run against a real Squid or Envoy in this repository. See the module caveat constant and the
README before trusting them in production.

The Python proxy in ``proxy.py`` is the reference implementation; these configs exist for
deployments where a managed Envoy or Squid is already the network choke point.
"""

from __future__ import annotations

import re
from typing import Any, cast

import yaml

from evalspleef.spi import NetMode

from .policy import Policy

CONFIG_CAVEAT = """\
# CAVEAT: generated by evalspleef-egress but not run against a real Squid or Envoy here.
# Validate with `squid -k parse` / `envoy --mode validate` before deployment.
"""

READ_ONLY_METHODS = ("GET", "HEAD", "CONNECT")


def _squid_host(pattern: str) -> str:
    """Squid ``dstdomain`` uses a leading dot for a suffix match."""
    if pattern.startswith("*."):
        return f".{pattern[2:]}"
    return pattern


def squid_conf(policy: Policy) -> str:
    """Emit a ``squid.conf`` expressing the policy.

    ``ssl_bump peek`` plus ``acl ... ssl::server_name`` filters TLS by SNI without decrypting
    traffic, which is what CONNECT-based clients need. Path-prefix allow entries and package
    mirror rewrites are not expressible in Squid's forward-proxy ACLs; the generated file
    enforces the host allowlist and the read-only method set only.
    """
    lines: list[str] = [
        CONFIG_CAVEAT.rstrip("\n"),
        f"# mode: {policy.mode.value}",
        "http_port 3128",
        "",
    ]
    if policy.mode is NetMode.OFF:
        lines.append("http_access deny all")
        return "\n".join(lines) + "\n"

    allowed = [_squid_host(pattern) for pattern, _ in policy.allow_rules]
    blocked = [_squid_host(pattern) for pattern in policy.block_rules]
    cidrs = " ".join(str(address) for address in policy.blocked_networks)

    if allowed:
        lines.append(f"acl allowed_hosts dstdomain {' '.join(allowed)}")
        lines.append(f"acl allowed_servers ssl::server_name {' '.join(allowed)}")
    if blocked:
        lines.append(f"acl blocked_hosts dstdomain {' '.join(blocked)}")
    if cidrs:
        lines.append(f"acl blocked_metadata dst {cidrs}")
    if policy.mode in (NetMode.DOCS_WHITELIST, NetMode.PACKAGE_MIRROR):
        lines.append(f"acl read_only_methods method {' '.join(READ_ONLY_METHODS)}")

    lines.append("")
    if blocked:
        lines.append("http_access deny blocked_hosts")
    if cidrs:
        lines.append("http_access deny blocked_metadata")
    if policy.mode in (NetMode.DOCS_WHITELIST, NetMode.PACKAGE_MIRROR):
        lines.append("http_access deny !read_only_methods")
    if policy.mode is NetMode.FULL:
        lines.append("http_access allow all")
    elif allowed:
        lines.append("http_access allow allowed_hosts")
        lines.append("http_access deny all")
        lines.extend(
            [
                "",
                "# Peek at the TLS ClientHello, then splice only allowlisted SNI names.",
                "ssl_bump peek all",
                "ssl_bump splice allowed_servers",
                "ssl_bump terminate all",
            ]
        )
    else:
        lines.append("http_access deny all")
    return "\n".join(lines) + "\n"


def _sni_pattern(host: str) -> str:
    """Envoy ``sni_dns_match`` pattern: exact name or ``*.suffix``."""
    return host


def _authority_regex(host: str) -> str:
    """Regex matching the HTTP ``:authority``/Host header for one allowlist host."""
    if host.startswith("*."):
        suffix = re.escape(host[2:])
        return rf"^[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.{suffix}(?::[0-9]+)?$"
    return rf"^{re.escape(host)}(?::[0-9]+)?$"


def _string_match(regex: str) -> dict[str, Any]:
    return {"safe_regex": {"google_re2": {}, "regex": regex}}


def _host_principal(host: str) -> dict[str, Any]:
    return {
        "or_ids": {
            "ids": [
                {"sni_dns_match": {"pattern": _sni_pattern(host)}},
                {
                    "header": {
                        "name": ":authority",
                        "string_match": _string_match(_authority_regex(host)),
                    }
                },
            ]
        }
    }


def _method_permission(policy: Policy) -> dict[str, Any]:
    if policy.mode is NetMode.FULL:
        return {"any": True}
    return {
        "and_rules": {
            "rules": [
                {
                    "header": {
                        "name": ":method",
                        "string_match": _string_match("^(GET|HEAD|CONNECT)$"),
                    }
                }
            ]
        }
    }


def _rbac_filter(name: str, rules: dict[str, Any]) -> dict[str, Any]:
    return {
        "name": "envoy.filters.http.rbac",
        "typed_config": {
            "@type": "type.googleapis.com/envoy.extensions.filters.http.rbac.v3.RBAC",
            "stat_prefix": name,
            "rules": rules,
        },
    }


def _network_rbac_filter(policy: Policy) -> dict[str, Any]:
    principals: list[dict[str, Any]] = []
    for network in policy.blocked_networks:
        principals.append(
            {
                "destination_ip": {
                    "address_prefix": str(network.network_address),
                    "prefix_len": network.prefixlen,
                }
            }
        )
    return {
        "name": "envoy.filters.network.rbac",
        "typed_config": {
            "@type": "type.googleapis.com/envoy.extensions.filters.network.rbac.v3.RBAC",
            "stat_prefix": "egress_destination_rbac",
            "rules": {
                "action": "DENY",
                "policies": {
                    "blocked_destinations": {
                        "permissions": [{"any": True}],
                        "principals": principals,
                    }
                },
            },
        },
    }


def envoy_yaml(policy: Policy) -> str:
    """Emit an Envoy bootstrap using ``sni_dynamic_forward_proxy`` and RBAC.

    The listener inspects TLS ClientHello SNI, the dynamic forward proxy cluster resolves the
    CONNECT target, and RBAC filters deny blocked hosts and allow only the policy allowlist.
    Metadata CIDRs are blocked by a network RBAC filter on the destination address.
    """
    allowed_hosts = [pattern for pattern, _ in policy.allow_rules]
    blocked_hosts = list(policy.block_rules)

    http_filters: list[dict[str, Any]] = [
        {
            "name": "envoy.filters.http.dynamic_forward_proxy",
            "typed_config": {
                "@type": (
                    "type.googleapis.com/envoy.extensions.filters.http."
                    "dynamic_forward_proxy.v3.DynamicForwardProxy"
                ),
                "dns_cache_config": {
                    "name": "egress_dns_cache",
                    "dns_lookup_family": "V4_ONLY",
                },
            },
        },
        {
            "name": "envoy.filters.http.sni_dynamic_forward_proxy",
            "typed_config": {
                "@type": (
                    "type.googleapis.com/envoy.extensions.filters.http."
                    "sni_dynamic_forward_proxy.v3.SniDynamicForwardProxy"
                ),
                "port_value": 443,
            },
        },
    ]

    if blocked_hosts:
        http_filters.append(
            _rbac_filter(
                "egress_block_rbac",
                {
                    "action": "DENY",
                    "policies": {
                        "blocklist": {
                            "permissions": [{"any": True}],
                            "principals": [_host_principal(host) for host in blocked_hosts],
                        }
                    },
                },
            )
        )

    if policy.mode is NetMode.OFF:
        allow_rules: dict[str, Any] = {
            "action": "DENY",
            "policies": {
                "deny_all": {
                    "permissions": [{"any": True}],
                    "principals": [{"any": True}],
                }
            },
        }
    elif policy.mode is NetMode.FULL:
        allow_rules = {
            "action": "ALLOW",
            "policies": {
                "allow_all": {
                    "permissions": [{"any": True}],
                    "principals": [{"any": True}],
                }
            },
        }
    else:
        allow_rules = {
            "action": "ALLOW",
            "policies": {
                "allowlist": {
                    "permissions": [_method_permission(policy)],
                    "principals": [_host_principal(host) for host in allowed_hosts],
                }
            },
        }
    http_filters.append(_rbac_filter("egress_allow_rbac", allow_rules))
    http_filters.append(
        {
            "name": "envoy.filters.http.router",
            "typed_config": {
                "@type": "type.googleapis.com/envoy.extensions.filters.http.router.v3.Router"
            },
        }
    )

    network_filters: list[dict[str, Any]] = []
    if policy.blocked_networks:
        network_filters.append(_network_rbac_filter(policy))
    network_filters.append(
        {
            "name": "envoy.filters.network.http_connection_manager",
            "typed_config": {
                "@type": (
                    "type.googleapis.com/envoy.extensions.filters.network."
                    "http_connection_manager.v3.HttpConnectionManager"
                ),
                "stat_prefix": "egress_proxy",
                "codec_type": "AUTO",
                "route_config": {
                    "name": "egress_route",
                    "virtual_hosts": [
                        {
                            "name": "dynamic_forward",
                            "domains": ["*"],
                            "routes": [
                                {
                                    "match": {"connect_matcher": {}},
                                    "route": {"cluster": "egress_dynamic_forward"},
                                },
                                {
                                    "match": {"prefix": "/"},
                                    "route": {"cluster": "egress_dynamic_forward"},
                                },
                            ],
                        }
                    ],
                },
                "http_filters": http_filters,
            },
        }
    )

    config: dict[str, Any] = {
        "static_resources": {
            "listeners": [
                {
                    "name": "egress",
                    "address": {"socket_address": {"address": "0.0.0.0", "port_value": 3128}},
                    "listener_filters": [{"name": "envoy.filters.listener.tls_inspector"}],
                    "filter_chains": [{"filters": network_filters}],
                }
            ],
            "clusters": [
                {
                    "name": "egress_dynamic_forward",
                    "lb_policy": "CLUSTER_PROVIDED",
                    "cluster_type": {
                        "name": "envoy.clusters.dynamic_forward_proxy",
                        "typed_config": {
                            "@type": (
                                "type.googleapis.com/envoy.extensions.clusters."
                                "dynamic_forward_proxy.v3.ClusterConfig"
                            ),
                            "dns_cache_config": {"name": "egress_dns_cache"},
                        },
                    },
                }
            ],
        }
    }
    body = yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=1000)
    return CONFIG_CAVEAT + body


def load_envoy_yaml(text: str) -> dict[str, Any]:
    """Parse generated Envoy YAML, ignoring the leading caveat comments."""
    data = yaml.safe_load(text)
    return cast(dict[str, Any], data)
